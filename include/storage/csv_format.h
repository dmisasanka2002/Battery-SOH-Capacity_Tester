#pragma once

#include <Arduino.h>


// ============================================================
// DATA RECORD
// ============================================================

struct DataRecord
{
    // --------------------------------------------------------
    // Time
    // --------------------------------------------------------

    String timestamp;

    uint32_t elapsedMs;


    // --------------------------------------------------------
    // Identification
    // --------------------------------------------------------

    uint16_t moduleNumber;

    uint32_t cycleNumber;


    // --------------------------------------------------------
    // Measurements
    // --------------------------------------------------------

    float voltage;

    float current;

    float batteryTemperature;

    float environmentTemperature;


    // --------------------------------------------------------
    // Test information
    // --------------------------------------------------------

    String mode;

    String method;
};


